import { strToU8, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { cleanPieceNameFromFileName, mapSlicerMaterial, parseSlicerBytes } from "./slicer-file-parser";

describe("parser local de archivos .3mf y .gcode", () => {
  it("limpia el nombre sugerido de archivo eliminando extensiones compuestas", () => {
    expect(cleanPieceNameFromFileName("soporte_gopro-v2.gcode.3mf")).toBe("soporte gopro v2");
    expect(cleanPieceNameFromFileName("LLAVERO_GATITO.gcode")).toBe("LLAVERO GATITO");
  });

  it("normaliza materiales de laminadores al catálogo del taller", () => {
    expect(mapSlicerMaterial("Bambu PLA Basic")).toBe("PLA");
    expect(mapSlicerMaterial("Prusament PETG")).toBe("PETG");
    expect(mapSlicerMaterial("TPU 95A")).toBe("TPU");
    expect(mapSlicerMaterial("eSUN ABS+")).toBe("ABS");
    expect(mapSlicerMaterial("Polymaker ASA")).toBe("ASA");
    expect(mapSlicerMaterial("PA12-CF")).toBe("OTHER");
  });

  it("extrae peso, tiempo, colores, material y purga desde .3mf laminado (slice_info.config)", () => {
    const xml = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="prediction" value="5400"/>
    <metadata key="weight" value="48.5"/>
    <metadata key="flush_weight" value="12"/>
    <filament id="1" type="PLA" used_g="30.2"/>
    <filament id="2" type="PLA" used_g="30.3"/>
  </plate>
</config>`;
    const zip = zipSync({ "Metadata/slice_info.config": strToU8(xml) });
    const parsed = parseSlicerBytes("Maceta_Bicolor.gcode.3mf", zip);

    expect(parsed.suggestedName).toBe("Maceta Bicolor");
    expect(parsed.grams).toBe(48.5);
    expect(parsed.printMinutes).toBe(90);
    expect(parsed.colorsCount).toBe(2);
    expect(parsed.purgeGrams).toBe(12);
    expect(parsed.material).toBe("PLA");
  });

  it("rechaza un .3mf de geometría sin laminar con mensaje claro", () => {
    const zip = zipSync({ "3D/3dmodel.model": strToU8("<model/>") });
    expect(() => parseSlicerBytes("modelo-crudo.3mf", zip)).toThrow(/no incluye datos de laminado/i);
  });

  it("extrae métricas desde un .gcode de PrusaSlicer / OrcaSlicer", () => {
    const gcode = `; generated by OrcaSlicer 2.1.0
; filament_type = PETG;PETG
; estimated printing time (normal mode) = 2h 15m 10s
; filament used [g] = 24.4, 15.6
G28
G1 X10 Y10
`;
    const parsed = parseSlicerBytes("pieza_funcional.gcode", strToU8(gcode));
    expect(parsed.slicer).toBe("OrcaSlicer");
    expect(parsed.grams).toBe(40);
    expect(parsed.printMinutes).toBe(135);
    expect(parsed.colorsCount).toBe(2);
    expect(parsed.material).toBe("PETG");
  });

  it("soporta tiempo de Cura (;TIME:) con peso explícito", () => {
    const gcode = `;Generated with Cura_SteamEngine 5.6.0
;TIME:3660
;Filament weight = 19.2
G28
`;
    const parsed = parseSlicerBytes("clip.gcode", strToU8(gcode));
    expect(parsed.slicer).toBe("Cura");
    expect(parsed.printMinutes).toBe(61);
    expect(parsed.grams).toBe(19.2);
  });
});
